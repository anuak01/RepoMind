import { Play } from "lucide-react";
import { useEffect, useState } from "react";
import { api, errMsg, Finding, OpenFn, Review as R } from "../api";
import { Timeline } from "../components/Timeline";
import { Empty, ErrorBox, PageHeader, Severity, Spinner, Tag } from "../components/ui";
import { useRun } from "../hooks/useRun";

function Card({ f, onOpen }: { f: Finding; onOpen: OpenFn }) {
  const [open, setOpen] = useState(false);
  const verified = f.origin === "verified";
  return (
    <div className="panel">
      <button className="flex w-full items-start gap-3 p-3 text-left" onClick={() => setOpen(!open)} aria-expanded={open}>
        <Severity level={f.severity} />
        <div className="min-w-0 flex-1"><div className="text-sm font-medium text-white">{f.title}</div><div className="font-mono text-xs text-slate-500">{f.path}:{f.line}</div></div>
        <Tag tone={verified ? "good" : "warn"}>{verified ? "Verified finding" : "AI suggestion"}</Tag><Tag>{f.category}</Tag>
      </button>
      {open && (
        <div className="space-y-3 border-t border-ink-700 p-3 text-sm">
          {f.snippet && <pre className="overflow-x-auto rounded bg-ink-950 p-2 font-mono text-xs text-slate-300">{f.line}: {f.snippet}</pre>}
          <p className="text-slate-300"><span className="text-slate-500">Issue: </span>{f.explanation}</p>
          <p className="text-slate-300"><span className="text-slate-500">Suggested fix: </span>{f.suggestion}</p>
          <p className="text-xs text-slate-500">{verified ? `Detected by static rule “${f.rule}” at this exact line.` : "Generated by an OpenRouter model after reading this code. Treat as a lead to confirm, not a confirmed defect."}</p>
          <button className="btn btn-ghost" onClick={() => onOpen(f.path, f.line, f.line)}>Open at line {f.line}</button>
        </div>)}
    </div>
  );
}

export default function Review({ repoId, onOpen }: { repoId: string; onOpen: OpenFn }) {
  const [data, setData] = useState<R | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [sev, setSev] = useState("all");
  const run = useRun();
  const load = () => api.get(`/repos/${repoId}/review`).then((r) => setData(r.data)).catch((e) => setError(errMsg(e)));
  useEffect(() => { setData(null); load(); }, [repoId]);
  if (error) return <div className="p-6"><ErrorBox message={error} /></div>;
  if (!data) return <div className="p-6"><Spinner /></div>;
  const keep = (f: Finding) => sev === "all" || f.severity === sev;
  const count = (s: string) => data.verified.filter((f) => f.severity === s).length;
  return (
    <div className="mx-auto max-w-4xl p-6">
      <PageHeader title="Code review" sub="Verified findings come from deterministic rules matched against real lines. AI suggestions are separate, labelled, and only kept if they point at code the agent actually read."
        right={<button className="btn btn-primary" disabled={run.running || !data.ai_enabled} title={data.ai_enabled ? "" : "Needs OPENROUTER_API_KEY"} onClick={async () => { await run.start(repoId, "review"); load(); }}><Play className="h-4 w-4" />{run.running ? "Reviewing…" : "Run AI review"}</button>} />
      <div className="mb-4 flex flex-wrap items-center gap-2">
        {["all", "high", "medium", "low"].map((s) => <button key={s} onClick={() => setSev(s)} className={`btn ${sev === s ? "btn-primary" : "btn-ghost"}`}>{s}{s !== "all" ? ` (${count(s)})` : ` (${data.verified.length})`}</button>)}
      </div>
      <h2 className="mb-2 text-sm font-semibold text-white">Verified findings</h2>
      <div className="space-y-2">{data.verified.filter(keep).map((f) => <Card key={f.id} f={f} onOpen={onOpen} />)}
        {data.verified.filter(keep).length === 0 && <Empty title="No verified findings" hint="The static rules did not match anything at this severity." />}</div>
      <h2 className="mb-2 mt-7 text-sm font-semibold text-white">AI suggestions <Tag tone="warn">unconfirmed</Tag></h2>
      <div className="space-y-2">{data.ai_suggestions.filter(keep).map((f) => <Card key={f.id} f={f} onOpen={onOpen} />)}
        {data.ai_suggestions.length === 0 && <Empty title="No AI suggestions yet" hint={data.ai_enabled ? "Run the AI review to let the Code Review Agent look for deeper issues." : "AI review is off because OPENROUTER_API_KEY is not set."} />}</div>
      {(run.events.length > 0 || run.running) && <div className="panel mt-6"><div className="border-b border-ink-700 px-4 py-2 text-sm font-semibold text-white">Agent activity</div><Timeline events={run.events} running={run.running} /></div>}
      {run.error && <div className="mt-4"><ErrorBox message={run.error} /></div>}
    </div>
  );
}
